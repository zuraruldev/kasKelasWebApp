-- 1. Buat Tabel cash_transactions
CREATE TABLE IF NOT EXISTS public.cash_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    jenis_transaksi VARCHAR(10) NOT NULL,
    nominal NUMERIC(12, 2) NOT NULL,
    keterangan TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    
    -- Constraint Integritas Data & Validasi Bisnis (Aturan TC-01)
    CONSTRAINT check_jenis_transaksi CHECK (jenis_transaksi IN ('Masuk', 'Keluar')),
    CONSTRAINT check_nominal_positif CHECK (nominal > 0)
);

-- Indeks untuk optimasi query pencarian dan pengurutan
CREATE INDEX IF NOT EXISTS idx_cash_transactions_tanggal ON public.cash_transactions(tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_cash_transactions_jenis ON public.cash_transactions(jenis_transaksi);

-- 2. Aktifkan Row Level Security (RLS)
ALTER TABLE public.cash_transactions ENABLE ROW LEVEL SECURITY;

-- 3. Hapus Policy Lama (Jika ada) untuk Menjamin Idempoten
DROP POLICY IF EXISTS "Allow public read access" ON public.cash_transactions;
DROP POLICY IF EXISTS "Allow public insert access" ON public.cash_transactions;
DROP POLICY IF EXISTS "Allow public update access" ON public.cash_transactions;
DROP POLICY IF EXISTS "Allow public delete access" ON public.cash_transactions;

-- 4. Buat Kebijakan Akses CRUD untuk Role anon & authenticated (Workshop Demo)
-- Policy READ (SELECT)
CREATE POLICY "Allow public read access"
ON public.cash_transactions
FOR SELECT
TO anon, authenticated
USING (true);

-- Policy CREATE (INSERT) dengan validasi constraint
CREATE POLICY "Allow public insert access"
ON public.cash_transactions
FOR INSERT
TO anon, authenticated
WITH CHECK (
    nominal > 0 
    AND jenis_transaksi IN ('Masuk', 'Keluar')
);

-- Policy UPDATE dengan validasi constraint
CREATE POLICY "Allow public update access"
ON public.cash_transactions
FOR UPDATE
TO anon, authenticated
USING (true)
WITH CHECK (
    nominal > 0 
    AND jenis_transaksi IN ('Masuk', 'Keluar')
);

-- Policy DELETE
CREATE POLICY "Allow public delete access"
ON public.cash_transactions
FOR DELETE
TO anon, authenticated
USING (true);

